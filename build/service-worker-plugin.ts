import { createHash } from 'node:crypto'
import { readdirSync } from 'node:fs'
import { posix, relative, sep } from 'node:path'
import type { Plugin } from 'vite'

const PRECACHEABLE = /\.(?:js|css|woff2|svg|png|webmanifest)$/

/** Static files under `public/` are copied verbatim and never appear in the bundle. */
function publicAssets(publicDir: string): string[] {
  try {
    return readdirSync(publicDir, { recursive: true, withFileTypes: true })
      .filter((entry) => entry.isFile() && PRECACHEABLE.test(entry.name))
      .map((entry) =>
        posix.join(relative(publicDir, entry.parentPath).split(sep).join('/'), entry.name),
      )
      .map((path) => path.replace(/^\//, ''))
  } catch {
    return []
  }
}

/**
 * Emits a dependency-free service worker that precaches the built app shell.
 *
 * Workbox pulls in a large dependency tree for behaviour RankRoom does not need:
 * the app is a single static bundle, so a precache list plus two fetch strategies
 * (cache-first for hashed assets, network-first for navigations) is the whole job.
 * The cache name embeds a hash of the precache list, so a new build evicts the old one.
 */
export function serviceWorkerPlugin(): Plugin {
  let base = '/'
  let publicDir = ''

  return {
    name: 'rankroom:service-worker',
    apply: 'build',
    configResolved(config) {
      base = config.base
      publicDir = config.publicDir
    },
    generateBundle(_options, bundle) {
      const assets = Object.keys(bundle)
        .filter((fileName) => PRECACHEABLE.test(fileName))
        .sort()

      // Fonts and icons live in public/, so they are copied rather than bundled;
      // without them the offline shell would render in a fallback typeface.
      const statics = publicAssets(publicDir).sort()

      const shell = [base, `${base}index.html`, `${base}offline.html`]
      const precache = [
        ...new Set([...shell, ...[...assets, ...statics].map((file) => base + file)]),
      ]
      const revision = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12)

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: renderServiceWorker({ base, precache, revision }),
      })
    },
  }
}

function renderServiceWorker(input: {
  base: string
  precache: string[]
  revision: string
}): string {
  const { base, precache, revision } = input

  return `// Generated by build/service-worker-plugin.ts — do not edit.
const CACHE = 'rankroom-${revision}'
const PRECACHE = ${JSON.stringify(precache, null, 2)}
const OFFLINE_URL = ${JSON.stringify(`${base}offline.html`)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      // addAll() is atomic: one 404 would leave the app with no cache at all.
      .then((cache) => Promise.all(PRECACHE.map((url) => cache.add(url).catch(() => undefined))))
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone()
          caches.open(CACHE).then((cache) => cache.put(request, copy))
          return response
        })
        .catch(() => caches.match(request).then((hit) => hit ?? caches.match(OFFLINE_URL)).then((hit) => hit ?? Response.error())),
    )
    return
  }

  event.respondWith(
    caches.match(request).then((hit) => {
      if (hit) return hit
      return fetch(request).then((response) => {
        if (response.ok && response.type === 'basic') {
          const copy = response.clone()
          caches.open(CACHE).then((cache) => cache.put(request, copy))
        }
        return response
      })
    }),
  )
})
`
}
